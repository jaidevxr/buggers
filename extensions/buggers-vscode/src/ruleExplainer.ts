import * as path from "path";
import { BuggersFinding } from "./types";

/**
 * Deterministic local rule explainer and test generator.
 * Operates 100% offline using verified rule metadata and source evidence.
 */
export class RuleExplainer {
  /**
   * Generates a comprehensive, formatted local rule explanation for a finding.
   */
  public explainFinding(finding: BuggersFinding): string {
    const fileName = path.basename(finding.file);
    const sevUpper = (finding.severity || "medium").toUpperCase();

    let out = `# [${sevUpper}] ${finding.title}\n\n`;
    out += `**Location:** \`${fileName}\` (Line ${finding.line}${finding.column !== undefined ? `, Col ${finding.column + 1}` : ""})\n\n`;
    out += `**Rule ID:** \`${finding.ruleId}\``;
    if (finding.cwe) out += ` | **CWE:** \`${finding.cwe}\``;
    if (finding.owasp) out += ` | **OWASP:** \`${finding.owasp}\``;
    out += `\n\n`;

    out += `## Problem Description\n\n${finding.problem}\n\n`;
    out += `## Why It Matters & Exploit Scenario\n\n${finding.whyItMatters}\n\n`;

    out += `## Vulnerable Code Detected\n\n\`\`\`javascript\n${finding.evidence}\n\`\`\`\n\n`;

    const fixCode = finding.replacementCode || finding.suggestedFix;
    out += `## Recommended Remediation\n\n\`\`\`javascript\n${fixCode}\n\`\`\`\n\n`;

    if (finding.replacementCode) {
      out += `> **Direct Fix Available:** This finding has a verified deterministic patch. Click **Fix Finding** in the Buggers sidebar or editor action menu to apply it directly.\n\n`;
    } else {
      out += `> **Manual Remediation Recommended:** No automated code transformation is defined for this rule. Apply the recommended pattern shown above.\n\n`;
    }

    out += `---\n*Generated by Buggers Local Security Engine (Deterministic Rule Verification).*`;
    return out;
  }

  /**
   * Generates an automated regression test template for the given finding.
   */
  public generateRegressionTest(finding: BuggersFinding): string {
    if (finding.regressionTest) {
      return finding.regressionTest;
    }

    const fileName = path.basename(finding.file);
    return `// Automated Regression Test for [${finding.ruleId}] ${finding.title}
// File: ${fileName} (Line ${finding.line})
// Target Vulnerability: ${finding.problem}

describe("Security Regression: ${finding.ruleId}", () => {
  it("prevents ${finding.problem}", async () => {
    // 1. Arrange: Provide representative input that previously triggered the finding
    const testInput = "safe_sanitized_input";

    // 2. Act: Execute function with the test input
    // const result = await targetFunction(testInput);

    // 3. Assert: Verify secure behavior
    expect(testInput).toBeDefined();
  });
});\n`;
  }
}
